import { parse } from 'yaml';

import { createGeneratorContainer } from '#~/di/container';
import { ConnectionPointGenerator } from '#~/engine/connection-points/connection-point-generator';
import { CONNECTION_POINT_KINDS } from '#~/enums/connection-point-kinds.enums';
import { GENERATOR_ERROR_CODES } from '#~/enums/generator-error-codes.enums';
import { HTTP_METHODS } from '#~/enums/http-methods.enums';
import { WEB_SLOTS } from '#~/enums/web-slots.enums';
import { moduleManifestSchema } from '#~/manifest/module-manifest.schema';
import type { iModuleManifestInput } from '#~/manifest/module-manifest.schema';

import { createManifest, testModuleId } from '../helpers/manifests';
import { REPOSITORY_ROOT } from '../helpers/temp-dir';

vi.mock('#~/enums/module-ids.enums', () => import('../helpers/test-module-ids'));

const ALPHA = testModuleId('alpha');
const BETA = testModuleId('beta');

const generator = createGeneratorContainer({ sourceRoot: REPOSITORY_ROOT, manifests: [] }).resolve(
  ConnectionPointGenerator,
);

async function generate(...inputs: iModuleManifestInput[]) {
  const modules = inputs.map((input) => moduleManifestSchema.parse(input));
  return generator.generate(modules, { installedModules: modules.map((manifest) => manifest.id) });
}

function fileContent(result: Awaited<ReturnType<typeof generate>>, filePath: string) {
  const file = result.files.find((candidate) => candidate.path === filePath);
  if (!file) throw new Error(`${filePath} was not generated`);
  return file.content;
}

describe('ConnectionPointGenerator', () => {
  it('builds one router map per workspace from every module, in module order', async () => {
    const result = await generate(
      createManifest(ALPHA, {
        contributions: [
          {
            kind: CONNECTION_POINT_KINDS.ROUTER,
            workspace: 'apps/server',
            key: 'user',
            router: { name: 'userRouter', from: '#~/routers/user.router' },
          },
        ],
      }),
      createManifest(BETA, {
        contributions: [
          {
            kind: CONNECTION_POINT_KINDS.ROUTER,
            workspace: 'apps/server',
            key: 'auth',
            router: { name: 'authRouter', from: '#~/routers/auth.router' },
          },
        ],
      }),
    );

    const content = fileContent(result, 'apps/server/src/generated/routers.ts');
    expect(content).toMatch(/^\/\/ Generated by create-tsukuri from starter\.json\. Do not edit/);
    expect(content).toContain(
      [
        "import { userRouter } from '#~/routers/user.router';",
        "import { authRouter } from '#~/routers/auth.router';",
        '',
        'export const generatedRouters = {',
        '  user: userRouter,',
        '  auth: authRouter,',
        '};',
      ].join('\n'),
    );
  });

  it('rejects two routers under the same key', async () => {
    const router = {
      kind: CONNECTION_POINT_KINDS.ROUTER,
      workspace: 'apps/server',
      key: 'user',
      router: { name: 'userRouter', from: '#~/a' },
    } as const;

    await expect(
      generate(createManifest(ALPHA, { contributions: [router] }), createManifest(BETA, { contributions: [router] })),
    ).rejects.toThrow(expect.objectContaining({ code: GENERATOR_ERROR_CODES.MERGE_CONFLICT }));
  });

  it('generates DI registrations with side-effect imports and token bindings', async () => {
    const content = fileContent(
      await generate(
        createManifest(ALPHA, {
          contributions: [
            {
              kind: CONNECTION_POINT_KINDS.DI_REGISTRATION,
              workspace: 'apps/server',
              imports: ['#~/db/postgres.service'],
              bindings: [
                {
                  token: { name: 'USER_REPOSITORY_TOKEN', from: '#~/di/tokens' },
                  implementation: { name: 'DrizzleUserRepository', from: '#~/features/user/drizzle-user.repository' },
                },
              ],
            },
          ],
        }),
      ),
      'apps/server/src/generated/di-registrations.ts',
    );

    expect(content).toContain("import { USER_REPOSITORY_TOKEN } from '#~/di/tokens';");
    expect(content).toContain('  [USER_REPOSITORY_TOKEN, DrizzleUserRepository],');
    expect(content).toContain("  await import('#~/db/postgres.service');");
  });

  it('generates an env schema per workspace and one root .env.example', async () => {
    const result = await generate(
      createManifest(ALPHA, {
        contributions: [
          {
            kind: CONNECTION_POINT_KINDS.ENV_VARIABLE,
            workspace: 'apps/server',
            name: 'POSTGRES_URL',
            schema: 'z.string().url()',
            example: 'postgresql://localhost/app',
          },
          {
            kind: CONNECTION_POINT_KINDS.ENV_VARIABLE,
            workspace: 'apps/web',
            name: 'VITE_SERVER_URL',
            schema: 'z.string()',
          },
        ],
      }),
    );

    expect(fileContent(result, 'apps/server/src/generated/env.schema.ts')).toContain(
      '  POSTGRES_URL: z.string().url(),',
    );
    expect(fileContent(result, '.env.example')).toContain(
      '\n# apps/server\nPOSTGRES_URL=postgresql://localhost/app\n\n# apps/web\nVITE_SERVER_URL=\n',
    );
  });

  it('builds the compose file, CI workflow and root scripts', async () => {
    const result = await generate(
      createManifest(ALPHA, {
        contributions: [
          { kind: CONNECTION_POINT_KINDS.CI_STEP, name: 'Verify', run: 'pnpm run verify --tests' },
          { kind: CONNECTION_POINT_KINDS.DEV_TASK, filter: 'server' },
          { kind: CONNECTION_POINT_KINDS.BUILD_TASK, filter: 'server' },
        ],
      }),
      createManifest(BETA, {
        contributions: [
          {
            kind: CONNECTION_POINT_KINDS.COMPOSE_SERVICE,
            name: 'postgres',
            service: { image: 'postgres:17' },
            volumes: ['postgres-data'],
          },
          { kind: CONNECTION_POINT_KINDS.DEV_TASK, filter: 'web' },
        ],
      }),
    );

    expect(parse(fileContent(result, 'docker-compose.dev.yml'))).toEqual({
      name: 'startername',
      services: { postgres: { image: 'postgres:17' } },
      volumes: { 'postgres-data': {} },
    });

    const workflow = parse(fileContent(result, '.github/workflows/ci.yml')) as {
      permissions: unknown;
      jobs: { verify: { steps: { run?: string }[] } };
    };
    expect(workflow.permissions).toEqual({ contents: 'read' });
    expect(workflow.jobs.verify.steps.at(-1)).toEqual({ name: 'Verify', run: 'pnpm run verify --tests' });

    expect(result.rootPackageJson.scripts).toEqual({
      build: 'pnpm --filter=server... run build',
      dev: 'docker compose -f ./docker-compose.dev.yml up -d --wait && pnpm --parallel --filter=server --filter=web run dev',
    });
  });

  it('generates the contract map, startup tasks, HTTP handlers and API context of a workspace', async () => {
    const result = await generate(
      createManifest(ALPHA, {
        contributions: [
          {
            kind: CONNECTION_POINT_KINDS.CONTRACT,
            workspace: 'packages/server-contract',
            key: 'index',
            contract: { name: 'indexContract', from: '../contract/index.contract' },
          },
          {
            kind: CONNECTION_POINT_KINDS.STARTUP_TASK,
            workspace: 'packages/api',
            task: { name: 'ConnectDatabaseTask', from: '#~/db/connect-database.task' },
          },
        ],
      }),
      createManifest(BETA, {
        contributions: [
          {
            kind: CONNECTION_POINT_KINDS.HTTP_HANDLER,
            workspace: 'packages/api',
            path: '/auth',
            methods: [HTTP_METHODS.GET, HTTP_METHODS.POST],
            handler: { name: 'handleAuthRequest', from: '#~/features/auth/auth.http' },
          },
          {
            kind: CONNECTION_POINT_KINDS.CONTEXT_PROVIDER,
            workspace: 'packages/api',
            provider: { name: 'provideSession', from: '#~/features/auth/auth.context' },
          },
        ],
      }),
    );

    expect(fileContent(result, 'packages/server-contract/src/generated/contracts.ts')).toContain(
      'export const generatedContracts = {\n  index: indexContract,\n};',
    );
    expect(fileContent(result, 'packages/api/src/generated/startup-tasks.ts')).toContain(
      'export const generatedStartupTasks = [\n  ConnectDatabaseTask,\n];',
    );
    expect(fileContent(result, 'packages/api/src/generated/http-handlers.ts')).toContain(
      "  { path: '/auth', methods: ['GET', 'POST'], handle: handleAuthRequest },",
    );
    const apiContext = fileContent(result, 'packages/api/src/generated/api-context.ts');
    expect(apiContext).toContain(
      'export type iGeneratedContext = Awaited<ReturnType<typeof provideSession>> & Record<never, never>;',
    );
    expect(apiContext).toContain('    ...(await provideSession(request)),');
  });

  it('generates the database schema and the error code enum with escaped messages', async () => {
    const result = await generate(
      createManifest(ALPHA, {
        contributions: [
          {
            kind: CONNECTION_POINT_KINDS.DATABASE_SCHEMA,
            workspace: 'packages/api',
            key: 'auth',
            from: '#~/features/auth/auth.schema',
          },
          {
            kind: CONNECTION_POINT_KINDS.ERROR_CODE,
            workspace: 'packages/common',
            code: 'USER_NOT_FOUND',
            message: "User isn't there",
          },
        ],
      }),
    );

    const databaseSchema = fileContent(result, 'packages/api/src/generated/database-schema.ts');
    expect(databaseSchema).toContain("import * as authSchema from '#~/features/auth/auth.schema';");
    expect(databaseSchema).toContain('  ...authSchema,');
    const errorCodes = fileContent(result, 'packages/common/src/generated/error-codes.ts');
    expect(errorCodes).toContain("  'USER_NOT_FOUND',");
    expect(errorCodes).toContain(`  [errorCodes.USER_NOT_FOUND, "User isn't there"],`);
  });

  it('rejects two modules declaring the same error code or handling the same path', async () => {
    const errorCode = {
      kind: CONNECTION_POINT_KINDS.ERROR_CODE,
      workspace: 'packages/common',
      code: 'BROKEN',
      message: 'Broken',
    } as const;

    await expect(
      generate(
        createManifest(ALPHA, { contributions: [errorCode] }),
        createManifest(BETA, { contributions: [errorCode] }),
      ),
    ).rejects.toThrow(expect.objectContaining({ code: GENERATOR_ERROR_CODES.MERGE_CONFLICT }));
  });

  it('generates a hosted connection point even when no module contributes to it', async () => {
    const result = await generate(
      createManifest(ALPHA, {
        hosts: [{ kind: CONNECTION_POINT_KINDS.STARTUP_TASK, workspace: 'packages/api' }],
      }),
    );

    expect(fileContent(result, 'packages/api/src/generated/startup-tasks.ts')).toContain(
      'export const generatedStartupTasks = [\n];',
    );
  });

  it('lists every web slot, with each module component in its slot', async () => {
    const result = await generate(
      createManifest(ALPHA, {
        contributions: [
          {
            kind: CONNECTION_POINT_KINDS.WEB_COMPONENT,
            workspace: 'apps/web',
            slot: WEB_SLOTS.HEADER_ACTIONS,
            component: { name: 'UserMenu', from: '#~/features/auth/components/user-menu' },
          },
        ],
      }),
    );

    const slots = fileContent(result, 'apps/web/src/generated/web-slots.ts');
    expect(slots).toContain("import { UserMenu } from '#~/features/auth/components/user-menu';");
    expect(slots).toContain('  HEADER_ACTIONS: [UserMenu],');
    expect(slots).toContain('  HEADER_NAVIGATION: [],');
  });

  it('generates nothing but a recursive build script when no module contributes', async () => {
    const result = await generate(createManifest(ALPHA));

    expect(result.files).toEqual([]);
    expect(result.rootPackageJson.scripts).toEqual({ build: 'pnpm --recursive run build' });
  });
});
