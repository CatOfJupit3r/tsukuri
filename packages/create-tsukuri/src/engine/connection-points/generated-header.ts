import { GENERATOR_NAME } from '#~/constants/generator-info';
import { PROJECT_RECORD_FILE } from '#~/record/project-record.schema';

export const GENERATED_HEADER = `Generated by ${GENERATOR_NAME} from ${PROJECT_RECORD_FILE}. Do not edit: changes are overwritten when modules are added or removed.`;

/** Folder, inside a workspace's `src`, that holds generated TypeScript connection points. */
export const GENERATED_SOURCE_DIR = 'src/generated';

export function withHashHeader(body: string) {
  return `# ${GENERATED_HEADER}\n\n${body}`;
}
